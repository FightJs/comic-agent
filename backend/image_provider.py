"""Durable one-image provider calls. No business adoption or automatic re-submission."""
import asyncio
import base64
import hashlib
import io
import json
import os
import re
from urllib.parse import urlparse
import httpx
from PIL import Image
from fastapi import HTTPException
from .store import uid,now,dump
from .capacity import CapacityPool
from .image_attempts import ImageAttempts,freeze_policy

MAX_IMAGE=20*1024*1024
MAX_RESPONSE=48*1024*1024


def atomic_write(path,raw):
    temporary=path.with_suffix(path.suffix+'.tmp')
    with temporary.open('wb') as output:
        output.write(raw);output.flush();os.fsync(output.fileno())
    os.replace(temporary,path)
    descriptor=os.open(path.parent,os.O_RDONLY)
    try:os.fsync(descriptor)
    finally:os.close(descriptor)


def inspect_image(raw):
    if not raw or len(raw)>MAX_IMAGE:raise ValueError('image_size')
    with Image.open(io.BytesIO(raw)) as image:
        if image.format not in ('PNG','JPEG','WEBP') or image.width*image.height>32000000:raise ValueError('image_format')
        info={'width':image.width,'height':image.height,'mime':Image.MIME[image.format],'format':image.format}
        image.verify()
    return info


class ImageProvider:
    def __init__(self,store,profile_get,secret_get,*,transport=None,credentials_get=None,slot=None):
        self.store,self.profile_get,self.secret_get=store,profile_get,secret_get
        self.transport=transport
        self.credentials_get=credentials_get
        self.slot=slot or CapacityPool(1)
        self.directory=store.root/'image-receipts';self.directory.mkdir(exist_ok=True)
        self.attempts=ImageAttempts(store)
        with store.db() as db:
            db.execute('CREATE TABLE IF NOT EXISTS image_calls(id TEXT PRIMARY KEY,project_id TEXT,operation_key TEXT,input_hash TEXT,manifest TEXT,status TEXT,result TEXT,error TEXT,created TEXT,updated TEXT,UNIQUE(project_id,operation_key))')
            db.execute("UPDATE image_calls SET status='unknown',error='应用重启：已提交调用结果待核对，不可自动重发' WHERE status='submitting'")

    def profile(self,config=None):
        config=(self.profile_get() if config is None else config) or {}
        public={k:config.get(k) for k in ('url','model')};public['api']=config.get('api') or 'openai-images'
        parsed=urlparse(public['url'] or '')
        if public['api']!='openai-images' or not public['model'] or parsed.scheme not in ('http','https') or not parsed.hostname or parsed.username or parsed.password or parsed.query or parsed.fragment:raise HTTPException(409,'请明确配置图像模型和OpenAI Images服务地址')
        if public['model'] in ('gpt-image-1','dall-e-2','dall-e-3'):raise HTTPException(422,'此型号已退役，请明确选择可用型号；不会自动替换')
        public['url']=public['url'].rstrip('/')
        return public

    def get(self,pid,cid):
        with self.store.db() as db:
            self.store.project(db,pid)
            row=db.execute('SELECT * FROM image_calls WHERE id=? AND project_id=?',(cid,pid)).fetchone()
            if not row:raise HTTPException(404,'图像调用不存在')
            result=dict(row);result['manifest']=json.loads(result['manifest']);result['result']=json.loads(result['result']) if result['result'] else None
            result['has_saved_response']=(self.directory/(cid+'.json')).is_file()
            grant=db.execute('SELECT call_id FROM image_attempt_grants WHERE call_id=? AND project_id=?',(cid,pid)).fetchone()
            result['attempts']=self.attempts.list(db,pid,cid) if grant else None
            return result

    def _reference(self,db,pid,ref):
        if not isinstance(ref,dict) or set(ref)!={'id','version'} or not isinstance(ref['id'],str) or type(ref['version']) is not int:raise HTTPException(422,'参考须为明确的记录和版本')
        r=self.store.get(db,pid,ref['id'],ref['version']);head=self.store.get(db,pid,ref['id'])
        if r['kind'] not in ('style','asset','image') or head['content'].get('deleted_by_script'):raise HTTPException(422,'参考须为未撤下的本项目图片')
        url=r['content'].get('url','');fid=url.rsplit('/',1)[-1]
        if url!=f'/api/projects/{pid}/files/{fid}' or not db.execute('SELECT id FROM files WHERE id=? AND project_id=?',(fid,pid)).fetchone():raise HTTPException(422,'参考图片必须来自当前项目文件')
        # Only file identifiers generated by Store.file may be resolved on disk.
        if not re.fullmatch(r'[0-9a-f]{32}(?:_0)?',fid):raise HTTPException(422,'图片文件编号无效')
        path=self.store.root/'files'/fid
        if path.stat().st_size>MAX_IMAGE:raise ValueError('image_size')
        raw=path.read_bytes();info=inspect_image(raw)
        return {**ref,'source':r['source'],'file_id':fid,'sha256':hashlib.sha256(raw).hexdigest(),'head_version':head['version'],'adopted':head['adopted'],'review':r['review'],**info}

    def prepare(self,pid,operation_key,prompt,*,refs=(),mask=None,options=None,source='ai',retry_policy=None):
        if source not in ('ai','mock'):raise HTTPException(422,'图像调用来源无效')
        if not isinstance(operation_key,str) or not 1<=len(operation_key)<=100 or not isinstance(prompt,str) or not 1<=len(prompt.strip())<=32000:raise HTTPException(422,'调用标识或图像提示词无效')
        if not isinstance(refs,(list,tuple)) or len(refs)>16:raise HTTPException(422,'最多16张明确参考图')
        supplied=options or {}
        params={'size':'1024x1536','quality':'auto','background':'opaque'}
        if not isinstance(supplied,dict) or set(supplied)-set(params):raise HTTPException(422,'尚不支持此图像参数')
        params.update(supplied)
        if params['size'] not in ('1024x1024','1024x1536','1536x1024') or params['quality'] not in ('auto','low','medium','high') or params['background'] not in ('opaque','transparent','auto'):raise HTTPException(422,'图像参数不在已支持范围')
        manifest={'provider':self.profile(),'prompt':prompt,'parameters':{**params,'n':1,'output_format':'png'},'operation':'edit' if refs else 'generate'}
        if retry_policy is not None:manifest['retry_policy']=freeze_policy(retry_policy)
        with self.store.db() as db:
            db.execute('BEGIN IMMEDIATE');self.store.project(db,pid)
            try:
                manifest['references']=[self._reference(db,pid,r) for r in refs]
                manifest['mask']=self._reference(db,pid,mask) if mask is not None else None
                manifest['source']='mock' if source=='mock' or any(r['source']=='mock' for r in manifest['references']+([manifest['mask']] if manifest['mask'] else [])) else 'ai'
                if mask is not None:
                    m=manifest['mask'];first=manifest['references'][0] if refs else None
                    if not first or m['format']!='PNG' or (m['width'],m['height'])!=(first['width'],first['height']) or (self.store.root/'files'/m['file_id']).stat().st_size>=4*1024*1024:raise ValueError('mask')
                    with Image.open(self.store.root/'files'/m['file_id']) as image:
                        if 'A' not in image.getbands() or image.getchannel('A').getextrema()[0]!=0:raise ValueError('mask_alpha')
            except (ValueError,OSError,Image.DecompressionBombError):raise HTTPException(422,'图片或蒙版不合规；蒙版须为同尺寸带透明区域PNG，不将文字批注当硬蒙版')
            signature=hashlib.sha256(json.dumps(manifest,ensure_ascii=False,sort_keys=True).encode()).hexdigest()
            previous=db.execute('SELECT id,input_hash FROM image_calls WHERE project_id=? AND operation_key=?',(pid,operation_key)).fetchone()
            if previous:
                if previous['input_hash']!=signature:raise HTTPException(409,'同一图像调用标识不可更换输入')
                cid=previous['id']
            else:
                cid=uid();stamp=now()
                db.execute('INSERT INTO image_calls VALUES(?,?,?,?,?,?,?,?,?,?)',(cid,pid,operation_key,signature,dump(manifest),'prepared',None,'',stamp,stamp))
        return self.get(pid,cid)

    def _status(self,pid,cid,status,error='',details=None):
        with self.store.db() as db:
            db.execute('UPDATE image_calls SET status=?,error=?,updated=? WHERE id=? AND project_id=?',(status,error,now(),cid,pid))
            if details is not None:db.execute('UPDATE image_calls SET result=? WHERE id=? AND project_id=?',(dump(details),cid,pid))
        return self.get(pid,cid)

    def _finalize(self,pid,cid):
        call=self.get(pid,cid)
        envelope=json.loads((self.directory/(cid+'.json')).read_text())
        if envelope.get('call_id')!=cid or envelope.get('input_hash')!=call['input_hash']:raise ValueError('receipt_binding')
        data=envelope['response'].get('data')
        if not isinstance(data,list) or len(data)!=1 or not isinstance(data[0].get('b64_json'),str):raise ValueError('image_response')
        raw=base64.b64decode(data[0]['b64_json'],validate=True);info=inspect_image(raw)
        if info['format']!='PNG':raise ValueError('unexpected_format')
        fid=cid+'_0';atomic_write(self.store.root/'files'/fid,raw)
        usage=envelope['response'].get('usage')
        valid_usage=isinstance(usage,dict) and all(type(usage.get(k)) is int and usage[k]>=0 for k in ('input_tokens','output_tokens','total_tokens'))
        result={'url':f'/api/projects/{pid}/files/{fid}',**info,'source':call['manifest']['source'],'sha256':hashlib.sha256(raw).hexdigest(),'request_id':envelope.get('request_id'),'usage':usage if valid_usage else None,'cost':None,'checked':False}
        with self.store.db() as db:
            db.execute('BEGIN IMMEDIATE')
            current=db.execute('SELECT status FROM image_calls WHERE id=? AND project_id=?',(cid,pid)).fetchone()
            if current['status']!='completed':
                db.execute('INSERT OR IGNORE INTO files VALUES(?,?,?,?)',(fid,pid,'生成图片.png','image/png'))
                db.execute("UPDATE image_calls SET status='completed',result=?,error='',updated=? WHERE id=?",(dump(result),now(),cid))
        return self.get(pid,cid)

    def _attempt_status(self,pid,cid,attempt,evidence,status,error='',details=None):
        if attempt is None:return self._status(pid,cid,status,error,details)
        with self.store.db() as db:
            db.execute('BEGIN IMMEDIATE')
            self.attempts.finish(db,pid,attempt['id'],evidence)
            db.execute('UPDATE image_calls SET status=?,error=?,updated=? WHERE id=? AND project_id=?',(status,error,now(),cid,pid))
            if details is not None:db.execute('UPDATE image_calls SET result=? WHERE id=? AND project_id=?',(dump(details),cid,pid))
        return self.get(pid,cid)

    async def execute(self,pid,cid,*,before_submit=None,authorization_hash=None,allow_retry=False):
        async with self.slot.hold(cid):
            call=self.get(pid,cid);receipt=self.directory/(cid+'.json')
            if call['status']=='completed':return call
            if receipt.exists():
                self._status(pid,cid,'received')
                try:return self._finalize(pid,cid)
                except (OSError,ValueError,KeyError,TypeError,Image.DecompressionBombError):return self._status(pid,cid,'received','已保存供应商返回，图片登记未完成；只恢复此返回，不重新请求')
            retry=call['status']=='not_sent' and allow_retry is True
            if call['status']!='prepared' and not retry:return call
            if retry and ('retry_policy' not in call['manifest'] or call['attempts'] is None):raise HTTPException(409,'旧调用缺少明确未发送尝试证据，不可自动重试')
            manifest=call['manifest'];profile=self.profile()
            if profile!=manifest['provider']:raise HTTPException(409,'图像配置已变化，请重新核对；未提交请求')
            with self.store.db() as db:
                for ref in manifest['references']+([manifest['mask']] if manifest['mask'] else []):
                    current=self._reference(db,pid,{'id':ref['id'],'version':ref['version']})
                    if current!=ref:raise HTTPException(409,'参考图片状态或文件已变化，未提交请求')
            try:
                if self.credentials_get:
                    config,secret=self.credentials_get()
                    if self.profile(config)!=profile:raise HTTPException(409,'图像配置已变化，未提交请求；请重新预览')
                else:secret=self.secret_get()
            except HTTPException:raise
            except Exception:raise HTTPException(503,'无法读取图像钥匙串；未提交请求')
            if not isinstance(secret,str) or not secret:raise HTTPException(409,'请先配置图像密钥；未提交请求')
            params={**manifest['parameters'],'model':profile['model'],'prompt':manifest['prompt']}
            kwargs={'json':params}
            if manifest['operation']=='edit':
                files=[]
                for n,r in enumerate(manifest['references']):
                    raw=(self.store.root/'files'/r['file_id']).read_bytes()
                    if hashlib.sha256(raw).hexdigest()!=r['sha256']:raise HTTPException(409,'参考文件已变化，未提交请求')
                    files.append(('image[]',(str(n)+'.'+{'PNG':'png','JPEG':'jpg','WEBP':'webp'}[r['format']],raw,r['mime'])))
                if manifest['mask']:
                    r=manifest['mask'];raw=(self.store.root/'files'/r['file_id']).read_bytes()
                    if hashlib.sha256(raw).hexdigest()!=r['sha256']:raise HTTPException(409,'蒙版文件已变化，未提交请求')
                    files.append(('mask',('mask.png',raw,'image/png')))
                kwargs={'data':{k:str(v) for k,v in params.items()},'files':files}
            with self.store.db() as db:
                db.execute('BEGIN IMMEDIATE')
                current=db.execute('SELECT status FROM image_calls WHERE id=? AND project_id=?',(cid,pid)).fetchone()
                if current['status']!=call['status']:return self.get(pid,cid)
                if self.profile()!=profile:raise HTTPException(409,'图像配置已变化，未提交请求；请重新预览')
                for ref in manifest['references']+([manifest['mask']] if manifest['mask'] else []):
                    if self._reference(db,pid,{'id':ref['id'],'version':ref['version']})!=ref:raise HTTPException(409,'参考图片状态或文件已变化，未提交请求')
                if before_submit:before_submit(db)
                attempt=None
                if 'retry_policy' in manifest:
                    if not isinstance(authorization_hash,str):raise HTTPException(409,'图像尝试缺少宿主明确冻结授权摘要')
                    if not retry:self.attempts.bind(db,pid,cid,call['input_hash'],authorization_hash,manifest['retry_policy'])
                    history=self.attempts.list(db,pid,cid)
                    attempt=self.attempts.claim(db,pid,cid,call['input_hash'],authorization_hash,len(history['attempts'])+1)
                    if not attempt['claimed']:return self.get(pid,cid)
                claimed=db.execute("UPDATE image_calls SET status='submitting',updated=? WHERE id=? AND project_id=? AND status=?",(now(),cid,pid,call['status'])).rowcount
            if not claimed:return self.get(pid,cid)
            endpoint='/images/edits' if manifest['operation']=='edit' else '/images/generations'
            diagnostics=None
            def terminal(status,error='',details=None,*,phase='unknown',error_class=None):
                evidence={'outcome':status,'response_started':diagnostics is not None,'transport_phase':phase}
                if error_class:evidence['error_class']=error_class
                if diagnostics:evidence['http_status']=diagnostics['http_status']
                if status=='received':evidence['receipt_sha256']=hashlib.sha256(receipt.read_bytes()).hexdigest()
                return self._attempt_status(pid,cid,attempt,evidence,status,error,details)
            try:
                async with httpx.AsyncClient(timeout=httpx.Timeout(300,connect=15),follow_redirects=False,trust_env=False,transport=self.transport) as client:
                    headers={'Authorization':'Bearer '+secret}
                    if attempt:headers['X-Client-Request-Id']=attempt['id']
                    async with client.stream('POST',profile['url']+endpoint,headers=headers,**kwargs) as response:
                        diagnostics={'http_status':response.status_code,'request_id':response.headers.get('x-request-id','').replace(secret,'[redacted]'),'usage':None,'cost':None}
                        if response.status_code!=200:
                            definite=400<=response.status_code<500 and response.status_code not in (408,409)
                        else:
                            body=bytearray()
                            async for chunk in response.aiter_bytes():
                                body.extend(chunk)
                                if len(body)>MAX_RESPONSE:raise ValueError('response_size')
                            value=json.loads(body)
                            def sanitize(v,key=''):
                                if isinstance(v,dict):return {k.replace(secret,'[redacted]'):sanitize(x,k) for k,x in v.items()}
                                if isinstance(v,list):return [sanitize(x,key) for x in v]
                                if isinstance(v,str):
                                    if key=='b64_json':
                                        # Image bytes stay exact; malformed strings are never persisted.
                                        inspect_image(base64.b64decode(v,validate=True));return v
                                    return v.replace(secret,'[redacted]')
                                return v
                            value=sanitize(value)
                            envelope={'call_id':cid,'input_hash':call['input_hash'],'request_id':response.headers.get('x-request-id','').replace(secret,'[redacted]'),'response':value}
                            if attempt:envelope['attempt_id']=attempt['id']
                            atomic_write(receipt,dump(envelope).encode())
            except (httpx.ConnectError,httpx.ConnectTimeout,httpx.PoolTimeout) as exc:
                # Exception names cannot erase evidence that a response already began.
                # Such failures may occur while reading/closing a custom transport.
                error_class='PoolTimeout' if isinstance(exc,httpx.PoolTimeout) else 'ConnectTimeout' if isinstance(exc,httpx.ConnectTimeout) else 'ConnectError'
                if diagnostics is not None:return terminal('unknown','已收到供应商响应但读取未完成；不可自动重发',diagnostics,phase='response_body',error_class=error_class)
                return terminal('not_sent','连接未建立；未自动重试',phase='pool_acquire' if isinstance(exc,httpx.PoolTimeout) else 'connect',error_class=error_class)
            except asyncio.CancelledError:
                terminal('unknown','请求中断，结果未知；不可自动重发',diagnostics,phase='response_body' if diagnostics else 'unknown',error_class='CancelledError');raise
            except Exception:return terminal('unknown','调用或返回持久化未完成，结果未知；不可自动重发',diagnostics,phase='response_body' if diagnostics else 'unknown')
            if diagnostics['http_status']!=200:
                return terminal('rejected' if definite else 'unknown','供应商拒绝请求；未自动重试' if definite else '供应商结果未知；不可自动重发',diagnostics,phase='response_headers')
            terminal('received',phase='response_body')
            try:return self._finalize(pid,cid)
            except (OSError,ValueError,KeyError,TypeError,Image.DecompressionBombError):return self._status(pid,cid,'received','已保存供应商返回，图片登记未完成；只恢复此返回，不重新请求')


def register_image_provider(app,store,vault_get):
    def profile():
        with store.db() as db:
            row=db.execute('SELECT content FROM settings WHERE id=1').fetchone()
            settings=json.loads(row['content']) if row else {}
            return settings if settings.get('purpose')=='image' else settings.get('image',{})
    def credentials():
        with app.state.config_lock:return profile(),vault_get('image')
    app.state.image_provider=ImageProvider(store,profile,lambda:vault_get('image'),credentials_get=credentials,slot=app.state.capacity.pools['image'])
